function portable(content, file) {
  return content.replace(/^---\n[\s\S]*?\n---\n/, '').replace(/\]\(([^)]+)\)/g, (match,href) => {
    if (/^(https?:|mailto:|data:)/.test(href)) return match;
    const [target, hash=''] = href.split('#');
    const dest = target.startsWith('/') ? path.join(docs,target) : path.resolve(path.dirname(file),target || path.basename(file));
    const relative = path.relative(docs,dest).replace(/\\/g,'/').replace(/\.md$/, '.html');
    return `](${origin}/${relative}${hash?'#'+hash:''})`;
  });
}
