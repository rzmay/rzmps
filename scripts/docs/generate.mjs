function distributionRegion(name) {
  const start=`<!-- distribution:${name}:start -->`, end=`<!-- distribution:${name}:end -->`;
  if(!distribution.includes(start)||!distribution.includes(end))throw new Error(`Missing distribution region ${name}`);
  return distribution.split(start)[1].split(end)[0].trim();
}
function readmeBlock(file, content) {
  const source=fs.readFileSync(path.join(root,file),'utf8');
  const start='<!-- RZMPS_AGENT_GUIDANCE_START -->',end='<!-- RZMPS_AGENT_GUIDANCE_END -->';
  const block=`${start}\n\n${banner}## AI Coding Assistants\n\n${content}\n\n${end}`;
  const existing=new RegExp(`${start}[\\s\\S]*?${end}`);
  emit(file,source.includes(start)?source.replace(existing,()=>block):source.replace('## Benchmarks',block+'\n\n## Benchmarks'));
}
