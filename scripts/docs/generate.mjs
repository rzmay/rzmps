import fs from 'node:fs';
import { docsUrl, skillUrl } from './site.mjs';
import { validateSkill } from './skill-format.mjs';
import { validatePreviews } from './preview-manifest.mjs';
import { generatePreviews } from './generate-previews.mjs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { root, discoverExamples, guideTemplate, validateGuide, resolveExample } from './examples.mjs';
import { guideNavigation, guideIndex } from './navigation.mjs';
import { apiNavigation, apiIndex } from './api-structure.mjs';

const check = process.argv.includes('--check');
const banner = '<!-- Generated by npm run docs:generate. Do not edit. -->\n\n';
const docs = path.join(root, 'apps/docs');
const origin = docsUrl.replace(/\/$/, '');
const outputs = new Map();
const emit = (file, content) => outputs.set(file, content);
function files(dir) { return fs.readdirSync(dir, {withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name,'en')).flatMap(e => e.isDirectory() ? files(path.join(dir,e.name)) : [path.join(dir,e.name)]); }
function removeEmptySubdirectories(directory) {
  for (const entry of fs.readdirSync(directory, {withFileTypes:true})) if (entry.isDirectory()) {
    const child = path.join(directory, entry.name);
    removeEmptySubdirectories(child);
    if (!fs.readdirSync(child).length) fs.rmdirSync(child);
  }
}
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'rzmps-docs-'));
try {
  execFileSync(process.execPath, [path.join(root,'node_modules/typedoc/bin/typedoc'), '--options', path.join(root,'typedoc.json'), '--out', temp], { cwd:root, stdio:'inherit' });
  for (const file of files(temp).filter(f=>f.endsWith('.md'))) emit(`apps/docs/api/${path.relative(temp,file)}`, banner + fs.readFileSync(file,'utf8'));
} finally { fs.rmSync(temp,{recursive:true,force:true}); }
const apiSections = apiNavigation(new Map([...outputs].map(([file,content])=>[file.replace('apps/docs/api/',''),content])), fs.readFileSync(path.join(root,'packages/rzmps/src/index.ts'),'utf8'));
emit('apps/docs/api/index.md', banner + apiIndex(apiSections));
emit('apps/docs/.vitepress/api.generated.json', JSON.stringify(apiSections,null,2)+'\n');
emit('apps/docs/guides/index.md', banner + guideIndex(guideNavigation(path.join(docs,'guides'))));
const examples = discoverExamples();
if (check) validatePreviews(examples);
const guides = new Map();
for (const example of examples) {
  const file = path.join(docs, 'examples', example.id+'.md');
  if (!fs.existsSync(file)) {
    if (check) throw new Error(`Missing authored guide: ${file}; run npm run docs:generate`);
    fs.mkdirSync(path.dirname(file),{recursive:true});
    fs.writeFileSync(file,guideTemplate(example),{flag:'wx'});
  }
  const content=fs.readFileSync(file,'utf8');
  if (!content.includes(`example: ${example.id}\n`)) throw new Error(`${file}: stale example frontmatter`);
  validateGuide(content,example,check);
  guides.set(file,resolveExample(content,example));
}
for (const file of files(path.join(docs,'examples')).filter(f=>f.endsWith('.md') && !f.endsWith('/index.md'))) if (!examples.some(e=>path.basename(file)===e.id+'.md')) throw new Error(`Stale example guide: ${file}`);
emit('examples/index.js', `// Generated by npm run docs:generate. Do not edit.\n`+examples.map((e,i)=>`import factory${i}, { metadata as metadata${i} } from './${e.file}';`).join('\n')+`\n\nexport const examples = [\n`+examples.map((e,i)=>`  { ...metadata${i}, create: factory${i}, sourceUrl: 'https://github.com/rzmay/rzmps/blob/develop/examples/${e.file}' },`).join('\n')+`\n];\n\nexport default Object.fromEntries(examples.map(({title, create, sourceUrl}) => {\n  create.sourceUrl = sourceUrl;\n  return [title, create];\n}));\n`);
emit('apps/docs/examples/index.md',banner+'# Examples\n\n'+examples.map(e=>`- [${e.title}](./${e.id}.md) — ${e.description} Preset by ${e.author.url ? `[${e.author.name}](${e.author.url})` : e.author.name}.`).join('\n')+'\n');
emit('apps/docs/.vitepress/examples.generated.json',JSON.stringify(examples.map(({regions,...e})=>e),null,2)+'\n');
const authored = files(path.join(docs,'guides')).filter(f=>f.endsWith('.md')&&!f.endsWith('/index.md'));
const pages = new Map(authored.map(f=>[f,fs.readFileSync(f,'utf8')]));
for (const [f,content] of guides) pages.set(f,content);
for (const f of ['index.md','contributing.md']) pages.set(path.join(docs,f),fs.readFileSync(path.join(docs,f),'utf8'));
for (const [f,content] of outputs) if (f.startsWith('apps/docs/api/') || f === 'apps/docs/examples/index.md' || f === 'apps/docs/guides/index.md') pages.set(path.join(root,f),content);
function portable(content, file) {
  return content.replace(/^---\n[\s\S]*?\n---\n/, '').replace(/\]\(([^)]+)\)/g, (match,href) => {
    if (/^(https?:|mailto:|data:)/.test(href)) return match;
    const [target, hash=''] = href.split('#');
    const dest = target.startsWith('/') ? path.join(docs,target) : path.resolve(path.dirname(file),target || path.basename(file));
    const relative = path.relative(docs,dest).replace(/\\/g,'/').replace(/\.md$/, '.html');
    return `](${origin}/${relative}${hash?'#'+hash:''})`;
  });
}
// Validate YAML now; validate all generated reference links once their outputs are assembled.
const skillPath=path.join(root,'.agents/skills/rzmps/SKILL.md');
const skill=fs.readFileSync(skillPath,'utf8');
const normalized=[...pages].sort(([a],[b])=>a.localeCompare(b,'en')).map(([f,c])=>[f,portable(c,f)]);
const consolidate = list => list.map(([f,c])=>`<!-- Source: ${path.relative(root,f)} -->\n\n${c}`).join('\n\n---\n\n');
const groups={
 'getting-started':normalized.filter(([f])=>f.endsWith('/first-particle-system.md')),
 'concepts':normalized.filter(([f])=>f.includes('/guides/')&&!f.endsWith('/first-particle-system.md')&&!f.endsWith('/compatibility.md')),
 'compatibility':normalized.filter(([f])=>f.endsWith('/compatibility.md')),
};
for(const [name,list] of Object.entries(groups))emit(`.agents/skills/rzmps/references/${name}.md`,banner+consolidate(list));
// Keep agent lookup pages small, with one source-derived reference per API/example page.
function referenceIndex(file, prefix) {
  return pages.get(path.join(docs,file)).replace(/\]\(([^)]+)\)/g, (match, href) => /^(https?:|mailto:|#)/.test(href) ? match : `](${prefix}/${href})`);
}
emit('.agents/skills/rzmps/references/api.md',referenceIndex('api/index.md','api'));
emit('.agents/skills/rzmps/references/examples.md',referenceIndex('examples/index.md','examples'));
for (const [file,content] of pages) {
  const relative=path.relative(docs,file).replace(/\\/g,'/');
  if(relative.startsWith('api/'))emit(`.agents/skills/rzmps/references/${relative}`,content);
  if(relative.startsWith('examples/')&&!relative.endsWith('/index.md'))emit(`.agents/skills/rzmps/references/${relative}`,banner+portable(content,file));
}
// Keep generated code blocks stable when editors trim trailing whitespace on save.
const fullDocumentation=(banner+consolidate(normalized)).replace(/^```[^\n]*\n[\s\S]*?^```[ \t]*$/gm,block=>block.replace(/[ \t]+$/gm,''));
emit('apps/docs/public/llms-full.txt',fullDocumentation);
const discoveryPages=['guides/first-particle-system.md','guides/index.md','guides/concepts.md','api/index.md','examples/index.md','guides/compatibility.md','guides/ai-coding-assistants.md','contributing.md'];
emit('apps/docs/public/llms.txt',banner+'# 🧅 RZMPS\n\nModular Three.js particles. Documentation for the develop branch.\n\n'+discoveryPages.map(relative=>{
  const content=pages.get(path.join(docs,relative));
  const title=content.match(/^# (.+)$/m)?.[1]??relative;
  return `- [${title}](${origin}/${relative.replace(/\.md$/,'.html')})`;
}).join('\n')+`\n- [Complete portable documentation](${origin}/llms-full.txt)\n`);
// Publish the canonical skill and references as raw portable Markdown, preserving YAML at the start.
const skillNotice='<!-- Generated from .agents/skills/rzmps/SKILL.md. Do not edit. -->';
emit('apps/docs/public/agent-skill/SKILL.md',skill.replace(/^(---\n[\s\S]*?\n---\n)/,`$1\n${skillNotice}\n`));
for(const [file,content] of [...outputs])if(file.startsWith('.agents/skills/rzmps/references/'))emit(file.replace('.agents/skills/rzmps/','apps/docs/public/agent-skill/'),content);
validateSkill(skillPath,new Map([...outputs].map(([file,content])=>[path.join(root,file),content])));
const template=fs.readFileSync(path.join(root,'scripts/docs/templates/npm-agents.md'),'utf8');
emit('packages/rzmps/AGENTS.md',banner+template.replaceAll('{{DOCS_URL}}',docsUrl).replaceAll('{{SKILL_URL}}',skillUrl));
const distribution=fs.readFileSync(path.join(docs,'guides/ai-coding-assistants.md'),'utf8');
function distributionRegion(name) {
  const start=`<!-- distribution:${name}:start -->`, end=`<!-- distribution:${name}:end -->`;
  if(!distribution.includes(start)||!distribution.includes(end))throw new Error(`Missing distribution region ${name}`);
  return distribution.split(start)[1].split(end)[0].trim();
}
function readmeBlock(file, content) {
  const source=fs.readFileSync(path.join(root,file),'utf8');
  const start='<!-- RZMPS_AGENT_GUIDANCE_START -->',end='<!-- RZMPS_AGENT_GUIDANCE_END -->';
  const block=`${start}\n\n${banner}## AI Coding Assistants\n\n${content}\n\n${end}`;
  const existing=new RegExp(`${start}[\\s\\S]*?${end}`);
  emit(file,source.includes(start)?source.replace(existing,()=>block):source.replace('## Benchmarks',block+'\n\n## Benchmarks'));
}
readmeBlock('README.md',distributionRegion('npm-readme')+'\n\n'+distributionRegion('installation'));
readmeBlock('packages/rzmps/README.md',distributionRegion('npm-readme'));
// Validate local Markdown targets, including generated API type links. VitePress also checks site links.
for (const [file, content] of pages) {
 const plain=content.replace(/```[\s\S]*?```/g,'');
 for(const match of plain.matchAll(/\]\(([^)]+)\)/g)) {
  const href=match[1].split('#')[0];
  if(!href||/^(https?:|mailto:|data:)/.test(href))continue;
  const target=href.startsWith('/')?path.join(docs,href):path.resolve(path.dirname(file),href);
  const candidates=[target,target+'.md',path.join(target,'index.md'),...(href.startsWith('/') ? [path.join(docs,'public',href)] : [])];
  // Preview assets are captured after the generated registry has been written.
  if(!check && href.startsWith('/previews/') && !candidates.some(p=>fs.existsSync(p))) continue;
  if(!candidates.some(p=>fs.existsSync(p)||outputs.has(path.relative(root,p))))throw new Error(`${file}: broken link ${href}`);
 }
}
// Detect removed generated pages as well as changed content without touching authored files.
const generatedDirs=['apps/docs/api','.agents/skills/rzmps/references','apps/docs/public/agent-skill'];
for(const dir of generatedDirs)if(fs.existsSync(path.join(root,dir)))for(const file of files(path.join(root,dir)))if(!outputs.has(path.relative(root,file))){
 if(check)throw new Error(`Stale generated artifact: ${file}`);
 fs.unlinkSync(file);
}
let differences=[];
for(const [file,content]of outputs){
 const dest=path.join(root,file);
 if(fs.existsSync(dest)&&fs.readFileSync(dest,'utf8')===content)continue;
 if(check)differences.push(file);
 else {fs.mkdirSync(path.dirname(dest),{recursive:true});fs.writeFileSync(dest,content);}
}
if(differences.length)throw new Error(`Generated documentation is out of date:\n${differences.join('\n')}\nRun npm run docs:generate.`);
if (!check) {
  // Renamed API sections must not leave empty folders in editors or prompt status caches.
  for (const directory of generatedDirs) removeEmptySubdirectories(path.join(root, directory));
  // Write the registry first so newly discovered factories are available to the capture harness.
  await generatePreviews();
  validatePreviews(examples);
}
console.log(`${check?'Checked':'Generated'} documentation for ${examples.length} shared examples and ${outputs.size} derived files.`);
