import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { docsUrl, skillUrl } from './site.mjs';
const root = path.resolve(import.meta.dirname, '../..');
export function packageAgents() {
  const template = fs.readFileSync(path.join(root, 'scripts/docs/templates/npm-agents.md'), 'utf8');
  return '<!-- Generated by npm run docs:generate. Do not edit. -->\n\n' + template.replaceAll('{{DOCS_URL}}', docsUrl).replaceAll('{{SKILL_URL}}', skillUrl);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, 'packages/rzmps/AGENTS.md'), packageAgents());
}
