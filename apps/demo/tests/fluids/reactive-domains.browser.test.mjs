import { browserLaunchOptions } from '../../../../scripts/browser/launch.utils.mjs';
import assert from 'node:assert/strict';
import path from 'node:path';
import puppeteer from 'puppeteer';
import { startSiteDev } from '../../../../scripts/site/dev.mjs';
import { openFixture } from './openFixture.mjs';

const site = await startSiteDev({ port: 0, host: '127.0.0.1' });
await site.demo.watcher.close();
let browser;
try {
  browser = await puppeteer.launch(browserLaunchOptions('test', { headless: true, args: [...browserLaunchOptions('test').args, '--enable-unsafe-webgpu'] }));
  const page = await browser.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const fixture = path.resolve(import.meta.dirname, 'fixtures/reactive-domains.html');
  await openFixture(page, `http://127.0.0.1:${site.demo.httpServer.address().port}/@fs${fixture}`, errors);
  const result = await page.evaluate(() => window.checkReactiveDomains());
  console.log(JSON.stringify(result));
  const guards = await page.evaluate(() => window.checkAdaptiveGuards());
  console.log('Adaptive guards:', JSON.stringify(guards));
  assert(guards.slow.every(face => face.guardBricks === 1));
  assert(guards.fast[3].guardBricks > 1);
  assert(guards.fast.filter((_, i) => i !== 3).every(face => face.guardBricks === 1));
  assert(guards.outlier[3].predictedTravel < guards.outlier[3].maximumTravel);
  assert(guards.dying[3].maximumTravel < 0.201);
  const liquidGuard = await page.evaluate(() => window.checkLiquidGuard());
  console.log('Liquid guard:', JSON.stringify(liquidGuard));
  assert(liquidGuard[3].guardBricks > 1 && liquidGuard[3].maximumTravel <= 5.001);
  assert.deepEqual(errors, []);
  assert(result.cachedStencilError < 1e-6, 'cached pressure stencil must match the original operator');
  assert(result.liquidStencilError < 1e-6, 'liquid free-surface stencil must match the original operator');
  assert(result.emptyCutoffReleased, 'zero cutoff must not retain empty gas bricks');
  assert(result.exact && result.overlap > 0, 'same-scale movement must preserve world cells exactly');
  assert(result.remapPreserved && result.pressureInvalidated, 'quality changes remap gas and invalidate pressure');
  assert(result.gasOnlyGuardRestored, 'gas alone must restore a full guard after source death');
  assert(result.gasSupportPreserved, 'occupied gas must remain in the forecast');
  assert(result.finite, 'rectangular pressure projection must remain finite');
  assert.deepEqual(result.queries, [0, 1]);
  assert(result.sourceError < 1e-6, 'coarse and fine source indices must give identical weighted contributions');
  assert(Math.abs(result.occupied[4] - 4.1) < 1e-6);
} finally { await browser?.close(); await site.close(); }
