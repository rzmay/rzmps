import { browserLaunchOptions } from '../../../../scripts/browser/launch.utils.mjs';
import assert from 'node:assert/strict';
import path from 'node:path';
import puppeteer from 'puppeteer';
import { startSiteDev } from '../../../../scripts/site/dev.mjs';
import { openFixture } from './openFixture.mjs';
const site = await startSiteDev({ port: 0, host: '127.0.0.1' });
await site.demo.watcher.close();
let browser;
try {
  browser = await puppeteer.launch(browserLaunchOptions('test', { headless: true, args: [...browserLaunchOptions('test').args, '--enable-unsafe-webgpu'], protocolTimeout: 45000 }));
  const page = await browser.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const file = path.resolve(import.meta.dirname, 'fixtures/gas-affectors.html');
  await openFixture(page, `http://127.0.0.1:${site.demo.httpServer.address().port}/@fs${file}`, errors);
  const result = await page.evaluate(() => window.runGasAffectorChecks());
  const close = (actual, expected) => assert(Math.abs(actual - expected) < 0.001, `${actual} != ${expected}`);
  assert(result.automaticallyDiscovered);
  close(result.nativeVelocity[0], 0.3);
  close(result.nativeState.density[0], 0.5);
  close(result.nativeState.density[1], 1.5);
  close(result.nativeState.color[0], 0.1);
  close(result.nativeState.color[1], 0.2);
  close(result.nativeState.color[2], 0.3);
  close(result.nativeVisual[0], 0.5);
  close(result.nativeVisual[1], 1.5);
  assert.deepEqual(result.nativePersistent, [1, 2, 0, 0]);
  close(result.excludedVelocity[0], 0);
  close(result.enabledVelocity[0], 0.2);
  close(result.disabledVelocity[0], 0);
  close(result.subsetVelocity[0], 0.2);
  close(result.broadVelocity[0], 0.4);
  close(result.broadDensity[0], 0.5);
  close(result.broadVisual[0], 0.5);
  close(result.broadPersistent[0], 1);
  close(result.broadDisabled[0], 0);
  close(result.forceVelocity[0], 0.2);
  close(result.thinForceVelocity[0], result.forceVelocity[0]);
  assert.deepEqual(result.order, ['velocity', 'projection', 'scalars']);
  close(result.persistent.density[0], 0.5); close(result.persistent.density[1], 1);
  close(result.persistent.color[0], 0.2); close(result.retained[0], 0.5);
  close(result.heated[1], 3); close(result.reheated[1], 4); close(result.moved[1], 2);
  close(result.tagged[1], 2); close(result.invertedCenter[1], 2);
  close(result.sourced.density[0], 1.2); close(result.sourced.density[1], 1.2);
  assert(result.sourced.color[1] > result.sourced.color[0]);
  close(result.dragged[0], 2 * Math.exp(-0.1));
  close(result.multiplied[0], 0.5); close(result.multiplied[1], 1);
  assert.deepEqual(result.killed.density, [0, 0, 0, 0]);
  assert.deepEqual(result.killed.color, [0, 0, 0, 0]);
  assert.deepEqual(result.transient.persistent, [1, 2, 0, 0]);
  close(result.transient.density[0], 0.25); close(result.transient.density[1], 0.75);
  close(result.transient.color[1], 0.25);
  assert.deepEqual(result.transient.repeated, result.transient.density);
  close(result.feather[0], 0.1); close(result.feather[1], -0.25); close(result.feather[2], -0.25);
  assert.deepEqual(result.transformed, [0, 0, 0, 0]);
  assert.deepEqual(result.benchmark.map(row => row.dispatches), [0, 20, 60]);
  assert.deepEqual(errors, []);
  const transport = await page.evaluate(() => window.checkForceTransport());
  assert(transport.samples.every(value => value <= transport.initial * 1.05),
    'a force must not create density in a source-free plume');
  assert(transport.samples.at(-1) > transport.initial * 0.8,
    'fading edge cells must not acquire singular acceleration and eject the plume');
  console.log(JSON.stringify({ transport }));
  console.log(JSON.stringify(result));
} finally { await browser?.close(); await site.close(); }
